"""
Kinematic Reachability and Collision Filtering for 6-DOF Grasp Candidates.

Evaluates candidate grasp poses generated by perception:
- Verifies DLS inverse kinematics convergence for Arm 1.
- Computes pre-grasp standoff poses along tool approach vectors.
- Enforces link-to-shelf clearance and inter-arm collision avoidance.
- Ranks viable candidates by combined perception score and kinematic manipulability.
"""

from typing import List, Tuple, Optional
from dataclasses import dataclass
import numpy as np
import mujoco
from control.kinematics import RobotKinematics
from control.collision_checker import CollisionChecker
from perception.grasp_planners.base_planner import GraspCandidate


@dataclass
class FilteredGrasp:
    """A verified, collision-free, kinematically reachable grasp execution plan."""
    candidate: GraspCandidate
    q_pregrasp: np.ndarray      # 6 joint angles for pre-grasp standoff
    q_grasp: np.ndarray         # 6 joint angles for target grasp
    pos_pregrasp: np.ndarray    # 3D position of pre-grasp
    pos_grasp: np.ndarray       # 3D position of target grasp
    standoff_dist: float
    is_valid: bool
    filter_score: float         # Composite ranking score


class GraspFilter:
    """Filters grasp candidates against physical kinematics and collision constraints."""

    def __init__(
        self,
        model: mujoco.MjModel,
        data: mujoco.MjData,
        arm_id: int = 1,
        standoff_dist: float = 0.15,
    ):
        self.model = model
        self.data = data
        self.arm_id = arm_id
        self.standoff_dist = standoff_dist
        self.kin = RobotKinematics(model, data, arm_id=arm_id)
        self.collision_checker = CollisionChecker(model, data)

    def filter_candidates(
        self,
        candidates: List[GraspCandidate],
        max_candidates_to_eval: int = 10,
    ) -> List[FilteredGrasp]:
        """
        Evaluates candidate grasps, filtering out unreachable or colliding poses.

        Returns:
            List of FilteredGrasp instances sorted by final score (highest first).
        """
        verified_grasps: List[FilteredGrasp] = []

        # Save starting simulation state
        saved_qpos = self.data.qpos.copy()
        saved_qvel = self.data.qvel.copy()
        q_home = self.kin.get_joint_positions()

        for cand in candidates[:max_candidates_to_eval]:
            pos_grasp = cand.pos
            quat_grasp = cand.quat
            approach_vec = cand.approach_dir / np.linalg.norm(cand.approach_dir)

            # Pre-grasp standoff pose along approach corridor
            pos_pregrasp = pos_grasp - self.standoff_dist * approach_vec

            # Helper to assign arm joints
            def set_arm_qpos(q):
                for i, addr in enumerate(self.kin.qpos_addrs):
                    self.data.qpos[addr] = q[i]

            # 1. Test IK for pre-grasp from home posture
            set_arm_qpos(q_home)
            mujoco.mj_forward(self.model, self.data)
            ok_pre, q_pre = self.kin.solve_ik_closed_loop(pos_pregrasp, quat_grasp)

            if not ok_pre:
                continue

            # 2. Test IK for grasp target from pre-grasp posture
            set_arm_qpos(q_pre)
            mujoco.mj_forward(self.model, self.data)
            ok_gr, q_gr = self.kin.solve_ik_closed_loop(pos_grasp, quat_grasp)

            if not ok_gr:
                continue

            # 3. Check shelf collisions at pre-grasp configuration
            set_arm_qpos(q_pre)
            mujoco.mj_step(self.model, self.data)
            coll_pre, _ = self.collision_checker.check_shelf_collision(self.arm_id)
            if coll_pre:
                continue

            # 4. Check shelf collisions at grasp configuration
            set_arm_qpos(q_gr)
            mujoco.mj_step(self.model, self.data)
            coll_gr, _ = self.collision_checker.check_shelf_collision(self.arm_id)
            if coll_gr:
                continue

            # 5. Compute composite score:
            # Rewards high perception confidence and lower joint displacement from home
            joint_disp = float(np.linalg.norm(q_pre - q_home))
            disp_penalty = np.exp(-0.1 * joint_disp)
            composite_score = cand.score * disp_penalty

            verified_grasps.append(FilteredGrasp(
                candidate=cand,
                q_pregrasp=q_pre,
                q_grasp=q_gr,
                pos_pregrasp=pos_pregrasp,
                pos_grasp=pos_grasp,
                standoff_dist=self.standoff_dist,
                is_valid=True,
                filter_score=composite_score,
            ))

        # Restore original state
        self.data.qpos[:] = saved_qpos
        self.data.qvel[:] = saved_qvel
        mujoco.mj_forward(self.model, self.data)

        # Sort descending by composite score
        verified_grasps.sort(key=lambda g: g.filter_score, reverse=True)
        return verified_grasps
